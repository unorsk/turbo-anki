#!/usr/bin/env python3
"""Generates TurboAnki/Core/UnicodeData.lean from Python's unicodedata.

Covers the scripts a vocabulary drill meets in practice (Latin, Greek, Cyrillic):
canonical pair decompositions, simple lowercase mappings, and the punctuation and
white space ranges that melk's `[\\p{P}\\s]` removes.
"""
import sys
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF), (0x1E00, 0x1FFF)]

def chars():
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            yield chr(cp)

decomp = []
for c in chars():
    d = unicodedata.decomposition(c)
    if not d or d.startswith("<"):
        continue
    parts = [int(p, 16) for p in d.split()]
    if len(parts) == 2 and unicodedata.combining(chr(parts[1])):
        decomp.append((ord(c), parts[0], parts[1]))

lower = []
for cp in list(range(0x00C0, 0x00DF)) + [cp for lo, hi in RANGES for cp in range(lo, hi + 1)]:
    c = chr(cp)
    l = c.lower()
    if len(l) == 1 and l != c and unicodedata.category(c) == "Lu":
        lower.append((cp, ord(l)))
lower = sorted(set(lower))

def ranges(pred, limit=0x3000):
    out, start = [], None
    for cp in range(limit + 1):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, limit))
    return out

punct = ranges(lambda c: unicodedata.category(c).startswith("P"))
space = ranges(lambda c: c.isspace() or unicodedata.category(c) == "Zs")

def arr(rows):
    return ",\n    ".join("(" + ", ".join(f"0x{v:04X}" for v in r) + ")" for r in rows)

print(f"""/-!
# Unicode data

Generated by `scripts/gen_unicode.py` from Python's `unicodedata` (Unicode
{unicodedata.unidata_version}); do not edit by hand. Covers Latin, Greek and Cyrillic.
-/

namespace TurboAnki.UnicodeData

/-- Canonical decompositions into a base character and one combining mark:
`(composed, base, mark)`. The base may itself decompose further. -/
def decompositions : Array (Nat × Nat × Nat) := #[
    {arr(decomp)}]

/-- Simple lowercase mappings of capital letters outside ASCII: `(upper, lower)`. -/
def lowercase : Array (Nat × Nat) := #[
    {arr(lower)}]

/-- Inclusive ranges of punctuation (general category `P*`) below U+3000. -/
def punctuation : Array (Nat × Nat) := #[
    {arr(punct)}]

/-- Inclusive ranges of white space below U+3000. -/
def whitespace : Array (Nat × Nat) := #[
    {arr(space)}]

end TurboAnki.UnicodeData""")
